// Concatenates supabase/migrations/*.sql into supabase/setup.sql so the whole
// database can be created with one paste in the Supabase SQL Editor.
// Run after changing a migration: npm run db:setup-file
import fs from 'node:fs';

const dir = new URL('./migrations/', import.meta.url);
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const header = `-- Suzy's Cleaners — complete database setup (generated by supabase/build-setup.mjs; do not edit).
--
-- Paste this whole file into Supabase → SQL Editor → New query, then press Run.
-- Run it once on a new project. It creates the tables, security rules, server
-- functions, push trigger, service catalog, settings and the demo logins:
--   Admin:    admin@suzyscleaners.com / SuzyAdmin2026!
--   Customer: demo@suzyscleaners.com  / Demo1234!
`;
const body = files.map((f) => `\n-- ═════════════════════════════════════════════ ${f}\n\n${fs.readFileSync(new URL(f, dir), 'utf8').trim()}\n`).join('');
fs.writeFileSync(new URL('./setup.sql', import.meta.url), header + body);
console.log(`Wrote supabase/setup.sql from ${files.length} migrations`);
